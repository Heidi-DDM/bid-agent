def region_from_title(title: str | None) -> str | None:
    """标题确定性地区抽取：命中河北地市/县级名 → 市口径 region；不命中 → None。

    纯子串命中（先市级后县级），不推断、不打分；标题未点名地区时返回 None，
    候选地区维持待详情回源。
    """
    if not title:
        return None
    for name, city in HEBEI_CITY_BY_NAME.items():
        if name in title:
            return city
    for county, city in HEBEI_CITY_BY_COUNTY.items():
        if county in title:
            return city
    return None
